function t(key) {
  var l = localStorage.getItem("khai_lang") || "en";
  var dict = LANG[l] || LANG.en;
  return dict[key] != null ? dict[key] : (LANG.en[key] != null ? LANG.en[key] : key);
}

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(function (node) {
    node.innerHTML = t(node.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(function (node) {
    node.setAttribute("placeholder", t(node.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(function (node) {
    node.setAttribute("title", t(node.getAttribute("data-i18n-title")));
  });
}

function setLang(l) {
  localStorage.setItem("khai_lang", l);
  applyI18n();
  var sel = document.getElementById("lang-select");
  if (sel) sel.value = l;
  if (typeof window._khai_on_lang === "function") window._khai_on_lang();
}